"""Тематический словарь ремонтов: из текста — набор узлов и видов работ.

Нужен для проверки «работы соответствуют проблеме» без LLM (mock-режим и подстраховка):
если в описании проблемы речь о подшипнике, а в работах — о кабеле, это видно и без модели.
"""

import re

# тема → основы слов (сравниваются с началом слова)
TOPICS: dict[str, tuple[str, ...]] = {
    "подшипник": ("подшип",),
    "течь/уплотнение": (
        "теч",
        "утеч",
        "уплотн",
        "манжет",
        "сальник",
        "рвд",
        "рукав",
        "протеч",
        "подтек",
    ),
    "лента конвейера": ("лент", "стык", "ролик", "барабан"),
    "редуктор": ("редуктор", "шестер", "зубчат", "зацеплен"),
    "футеровка": ("футеров", "брон", "плит"),
    "металлоконструкция": ("трещин", "свар", "завар", "шов", "шва", "рам", "косынк", "наклад"),
    "крепёж/вибрация": ("крепёж", "крепеж", "болт", "гайк", "вибрац", "протян", "затяж", "люфт"),
    "электродвигатель": ("двигател", "электродвиг", "мотор", "обмотк"),
    "пускатель/автомат": ("пускател", "контактор", "автомат", "магнитн", "реле", "щит"),
    "кабель": ("кабел", "провод", "изоляц", "пробо", "искрен"),
    "защита/КЗ": ("защит", "замыкан", "кз", "предохранит", "выбива"),
    "датчик": ("датчик", "сигнал", "кип", "уровн"),
    "гидронасос/давление": ("насос", "давлен", "гидравл", "гидро"),
    "масло": ("масл", "долит", "залит", "слит"),
    "фильтр": ("фильтр",),
    "пневматика": ("воздух", "пневм", "цилиндр", "распредел", "фитинг", "шипит"),
    "смазка": ("смаз", "солидол", "литол", "маслёнк", "масленк", "сух"),
}

# Общие темы встречаются почти в любой заявке — они весят меньше конкретных («течь», «подшипник»)
GENERIC_TOPICS = frozenset({"масло", "гидронасос/давление", "крепёж/вибрация"})

_WORD = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)


def topic_weight(topic: str) -> float:
    return 0.5 if topic in GENERIC_TOPICS else 1.0


def weighted_overlap(problem: set[str], other: set[str]) -> float:
    """Доля «веса» тем проблемы, которая есть и в другом тексте (0..1)."""
    total = sum(topic_weight(t) for t in problem)
    if not total:
        return 0.0
    return sum(topic_weight(t) for t in problem & other) / total


def topics_of(text: str) -> set[str]:
    words = [w.lower() for w in _WORD.findall(text)]
    found = set()
    for topic, stems in TOPICS.items():
        if any(word.startswith(stem) for word in words for stem in stems):
            found.add(topic)
    return found


def overlap(problem: str, works: str) -> tuple[float, set[str], set[str]]:
    """Доля тем проблемы, которые закрыты в работах; темы проблемы; темы работ."""
    p, w = topics_of(problem), topics_of(works)
    if not p:
        return (0.5 if w else 0.4), p, w
    return len(p & w) / len(p), p, w
